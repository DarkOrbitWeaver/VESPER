using VESPER;
using Vesper.MediaResolver.Formats;
using Vesper.MediaResolver.Models;

namespace Vesper.Windows.Tests;

public sealed class MediaDiscoveryFormTests
{
    [Fact]
    public void SubtitleLanguagesStayOffUntilCheckedAndSupportMultipleSelections()
    {
        SubtitleTrack[] options =
        [
            new(new Uri("https://cdn.example.test/en.vtt"), "en", "English", "vtt"),
            new(new Uri("https://cdn.example.test/fr.srt"), "fr", "French", "srt"),
            new(new Uri("https://cdn.example.test/es.vtt"), "es", "Spanish", "vtt", IsAutoGenerated: true)
        ];

        FormatPreferences off = MediaDiscoveryForm.WithSubtitleSelection(FormatPreferences.BestQuality, options, []);
        FormatPreferences several = MediaDiscoveryForm.WithSubtitleSelection(FormatPreferences.BestQuality, options, [0, 1, 1, -1, 9]);
        FormatPreferences generated = MediaDiscoveryForm.WithSubtitleSelection(FormatPreferences.BestQuality, options, [0, 2]);

        Assert.Empty(off.SubtitleLanguages);
        Assert.False(off.IncludeAutoSubtitles);
        Assert.Equal(new[] { "en", "fr" }, several.SubtitleLanguages);
        Assert.False(several.IncludeAutoSubtitles);
        Assert.Equal(new[] { "en", "es" }, generated.SubtitleLanguages);
        Assert.True(generated.IncludeAutoSubtitles);
    }
}
