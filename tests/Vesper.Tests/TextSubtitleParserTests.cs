using System.Text;
using Vesper.Engine;

namespace Vesper.Tests;

public sealed class TextSubtitleParserTests
{
    [Fact]
    public void SrtCuesBecomeUtf8MatroskaSubtitleSamples()
    {
        const string srt = "1\r\n00:00:01,250 --> 00:00:02,500\r\nFirst line\r\nSecond line\r\n\r\n"
            + "2\r\n00:00:03,000 --> 00:00:03,750\r\nNext cue\r\n";

        ParsedSubtitle parsed = TextSubtitleParser.Parse(Encoding.UTF8.GetBytes(srt), "srt", "en-US", "English", 5);
        using MemoryStream source = parsed.Source;

        Assert.Equal(TrackKind.Subtitle, parsed.Track.Kind);
        Assert.Equal("utf8", parsed.Track.Codec);
        Assert.Equal("S_TEXT/UTF8", parsed.Track.MatroskaCodecId);
        Assert.Equal("en-US", parsed.Track.Language);
        Assert.Equal("English", parsed.Track.Name);
        Assert.Equal(1000u, parsed.Track.Timescale);
        Assert.Equal([1250L, 3000L], parsed.Track.Samples.Select(sample => sample.Dts));
        Assert.Equal([1250, 750], parsed.Track.Samples.Select(sample => sample.Duration));
        Assert.Equal(Encoding.UTF8.GetByteCount("First line\nSecond lineNext cue"), parsed.Track.PayloadBytes);
    }

    [Fact]
    public void WebVttNotesAreIgnoredAndMultilineCuesKeepTimes()
    {
        const string vtt = "WEBVTT - captions\n\nNOTE generated by fixture\nignored\n\n"
            + "cue-a\n00:00.5 --> 00:02.250\nHello\nworld\n";

        ParsedSubtitle parsed = TextSubtitleParser.Parse(Encoding.UTF8.GetBytes(vtt), "vtt", "fr", "French", 3);
        using MemoryStream source = parsed.Source;

        TrackSample cue = Assert.Single(parsed.Track.Samples);
        Assert.Equal(500, cue.Dts);
        Assert.Equal(1750, cue.Duration);
        byte[] text = new byte[cue.Size];
        source.Position = cue.Offset;
        Assert.Equal(cue.Size, source.Read(text));
        Assert.Equal("Hello\nworld", Encoding.UTF8.GetString(text));
    }

    [Theory]
    [InlineData("00:00:02,000 --> 00:00:03,000", "00:00:01,000 --> 00:00:01,500")]
    [InlineData("00:00:01,000 --> 00:00:01,000", null)]
    public void InvalidSrtTimingIsRejected(string firstTiming, string? secondTiming)
    {
        string text = "1\n" + firstTiming + "\nFirst\n\n";
        if (secondTiming is not null) text += "2\n" + secondTiming + "\nSecond\n";

        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(
            Encoding.UTF8.GetBytes(text), "srt", "en", "English", 10));
    }

    [Fact]
    public void UnsupportedEncodingAndOutOfRangeCuesAreRejected()
    {
        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(
            [0xFF, 0xFE, 0x31, 0x00], "srt", "en", "English", 10));

        const string lateCue = "1\n00:00:09,000 --> 00:00:10,000\nToo late\n";
        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(
            Encoding.UTF8.GetBytes(lateCue), "srt", "en", "English", 5));
    }

    [Fact]
    public void WebVttPresentationSettingsAndStylingAreRejected()
    {
        const string positioned = "WEBVTT\n\n00:00.000 --> 00:02.000 align:start\nText\n";
        const string styled = "WEBVTT\n\nSTYLE\n::cue { color: white; }\n\n00:00.000 --> 00:02.000\nText\n";

        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(
            Encoding.UTF8.GetBytes(positioned), "vtt", "en", "English", 3));
        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(
            Encoding.UTF8.GetBytes(styled), "vtt", "en", "English", 3));
    }

    [Fact]
    public void SrtCanBecomeMp4Tx3gWithClearSamplesForGaps()
    {
        const string srt = "1\n00:00:00,500 --> 00:00:01,000\nFirst\n\n"
            + "2\n00:00:02,000 --> 00:00:02,500\nSecond\n";

        ParsedSubtitle parsed = TextSubtitleParser.Parse(Encoding.UTF8.GetBytes(srt), "srt", "en-US", "English", 3,
            outputContainer: "mp4", videoWidth: 1280, videoHeight: 720);
        using MemoryStream source = parsed.Source;

        Assert.Equal("tx3g", parsed.Track.Codec);
        Assert.Equal("mp4", parsed.Track.SourceContainer);
        Assert.NotNull(parsed.Track.Mp4SampleEntry);
        Assert.Equal("eng", parsed.Track.Language);
        Assert.Equal([500L, 1000L, 2000L, 2500L], parsed.Track.Samples.Select(sample => sample.Dts));
        Assert.Equal([500, 1000, 500, 500], parsed.Track.Samples.Select(sample => sample.Duration));
        Assert.Equal(3_000L, parsed.Track.Samples[^1].Dts + parsed.Track.Samples[^1].Duration);
        byte[] firstSample = new byte[parsed.Track.Samples[0].Size];
        source.Position = parsed.Track.Samples[0].Offset;
        Assert.Equal(firstSample.Length, source.Read(firstSample));
        Assert.Equal((ushort)5, System.Buffers.Binary.BinaryPrimitives.ReadUInt16BigEndian(firstSample));
        Assert.Equal("First", Encoding.UTF8.GetString(firstSample, 2, 5));
    }

    [Fact]
    public void StyledTextStaysOutOfTx3gAndUnrepresentableDurationsAreRejected()
    {
        const string styled = "1\n00:00:00,000 --> 00:00:01,000\n<b>Bold</b>\n";
        const string longCue = "1\n00:00:00,000 --> 600:00:00,000\nToo long\n";

        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(Encoding.UTF8.GetBytes(styled),
            "srt", "en", "English", 2, outputContainer: "mp4", videoWidth: 1280, videoHeight: 720));
        Assert.Throws<MediaContainerException>(() => TextSubtitleParser.Parse(Encoding.UTF8.GetBytes(longCue),
            "srt", "en", "English", null));
    }

    [Fact]
    public void SubtitleMergePlansRequireSupportedOutputAndBoundedSafeTracks()
    {
        var original = new MediaMergePlan
        {
            Version = 3,
            Provider = "test",
            MediaId = "captions",
            OutputContainer = "mkv",
            RequireAudio = true,
            RequireVideo = true,
            Tracks =
            [
                new MergeTrack("video", "video", "https://cdn.example/video.mp4", 100, "mp4", "h264", "video-id"),
                new MergeTrack("audio", "audio", "https://cdn.example/audio.m4a", 50, "m4a", "aac", "audio-id")
            ],
            Subtitles = [new MergeSubtitle("https://cdn.example/en.srt", "srt", "en-US", "English")]
        };

        Assert.True(MediaMergePlan.TryParse(original.ToJson(), false, out _, out _));
        Assert.False(MediaMergePlan.TryParse((original with { Version = 1 }).ToJson(), false, out _, out _));
        Assert.True(MediaMergePlan.TryParse((original with { OutputContainer = "mp4" }).ToJson(), false, out _, out _));
        Assert.False(MediaMergePlan.TryParse((original with { OutputContainer = "webm" }).ToJson(), false, out _, out _));
        Assert.False(MediaMergePlan.TryParse((original with
        {
            Subtitles = [new MergeSubtitle("https://cdn.example/en.srt", "srt", "en_US")]
        }).ToJson(), false, out _, out _));
        Assert.False(MediaMergePlan.TryParse((original with
        {
            Subtitles = [new MergeSubtitle("http://127.0.0.1/en.srt", "srt", "en")]
        }).ToJson(), false, out _, out _));
        Assert.False(MediaMergePlan.TryParse((original with { ClipRange = new MediaTimeRange(1, 2) }).ToJson(), false, out _, out _));
    }

    [Fact]
    public void SubtitleFingerprintBindsQueryIdentityWithoutExposingItsValue()
    {
        var first = new MediaMergePlan
        {
            Version = 3,
            Provider = "test",
            MediaId = "caption-query",
            OutputContainer = "mkv",
            RequireAudio = true,
            RequireVideo = true,
            Tracks =
            [
                new MergeTrack("video", "video", "https://cdn.example/video.mp4", 100, "mp4", "h264", "video-id"),
                new MergeTrack("audio", "audio", "https://cdn.example/audio.m4a", 50, "m4a", "aac", "audio-id")
            ],
            Subtitles = [new MergeSubtitle("https://cdn.example/en.srt?token=private-first", "srt", "en")]
        };
        MediaMergePlan changed = first with
        {
            Subtitles = [new MergeSubtitle("https://cdn.example/en.srt?token=private-second", "srt", "en")]
        };
        Assert.True(MediaMergePlan.TryParse(first.ToJson(), false, out MediaMergePlan restored, out string error), error);

        Assert.Equal(first.Fingerprint, restored.Fingerprint);
        Assert.NotEqual(first.Fingerprint, changed.Fingerprint);
        Assert.False(first.CanContinueWith(changed, out _));
        Assert.DoesNotContain("private-first", first.Fingerprint, StringComparison.Ordinal);
        Assert.DoesNotContain("private-second", changed.Fingerprint, StringComparison.Ordinal);
    }
}
